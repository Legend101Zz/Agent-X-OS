#!/usr/bin/env node
/**
 * build-docs-content.mjs — Generate a TS module embedding the four design docs
 * (BLUEPRINT, MANDATE, README, ARCHITECTURE) as string constants.
 *
 * Run from the dashboard/ directory:
 *   node scripts/build-docs-content.mjs
 *
 * Reads docs/*.md relative to the repo root (one level up from dashboard/),
 * then writes dashboard/src/lib/docs/registry.content.ts with a default-export
 * object keyed by doc slug.
 *
 * Why we embed: the docs page is a static read-only view. Embedding the text
 * into the bundle keeps prerendering simple, makes the source path in the UI
 * purely informational, and means the build doesn't depend on filesystem
 * layout at runtime.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..", "..");
const outFile = resolve(
  __dirname,
  "..",
  "src",
  "lib",
  "docs",
  "registry.content.ts",
);

const docs = [
  { slug: "blueprint", source: "BLUEPRINT.md" },
  { slug: "mandate", source: "MANDATE.md" },
  { slug: "readme", source: "README.md" },
  { slug: "architecture", source: "ARCHITECTURE.md" },
];

function jsString(value) {
  // JSON.stringify handles escapes correctly and is deterministic.
  return JSON.stringify(value);
}

const lines = [];
lines.push("// AUTO-GENERATED by scripts/build-docs-content.mjs — do not edit by hand.");
lines.push("// Re-run `node scripts/build-docs-content.mjs` from dashboard/ to refresh.");
lines.push("/**");
lines.push(" * Embedded design docs. Each entry holds the raw markdown text used to");
lines.push(" * derive headings, sections, and concept explainers in registry.ts.");
lines.push(" */");
lines.push("export interface DocContent {");
lines.push("  slug: string;");
lines.push("  sourcePath: string;");
lines.push("  raw: string;");
lines.push("}");
lines.push("");
lines.push("export const DOC_CONTENT: Record<string, DocContent> = {");
for (const d of docs) {
  const filePath = join(repoRoot, "docs", d.source);
  const raw = readFileSync(filePath, "utf8");
  lines.push(`  ${jsString(d.slug)}: {`);
  lines.push(`    slug: ${jsString(d.slug)},`);
  lines.push(`    sourcePath: ${jsString(`../docs/${d.source}`)},`);
  lines.push(`    raw: ${jsString(raw)},`);
  lines.push("  },");
}
lines.push("};");
lines.push("");

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`Wrote ${outFile} (${docs.length} docs, ${(lines.join("\n").length / 1024).toFixed(1)} KB)`);
